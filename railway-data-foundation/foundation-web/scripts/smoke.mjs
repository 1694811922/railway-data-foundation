import { createServer } from 'vite'
import { chromium } from 'playwright-core'
import { mkdir } from 'node:fs/promises'
import { join } from 'node:path'

const browserPath = process.env.FOUNDATION_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'
// The UI smoke exercises the stable report fixture; live API behavior is covered by MySQL integration tests.
if (process.env.SMOKE_EXPECT_REAL_SOURCE !== 'true') process.env.VITE_USE_MOCK = 'true'
const server = await createServer({ server: { host: '127.0.0.1', port: 5174, strictPort: true } })
let browser
try {
  await server.listen()
  browser = await chromium.launch({ executablePath: browserPath, headless: true })
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, locale: 'zh-CN' })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5174/', { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: '进入平台' }).click()
  await page.getByRole('heading', { name: '首页概览' }).waitFor()
  await page.getByText('已接入数据源').waitFor()

  await page.goto('http://127.0.0.1:5174/sources', { waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: '数据源管理' }).waitFor()
  if (process.env.SMOKE_EXPECT_REAL_SOURCE === 'true') {
    await page.getByText('广州港业务数据库').first().waitFor()
    if (await page.getByText('后端不可用时展示演示数据').count()) throw new Error('Expected real Source API, got demo fallback')
    await page.getByRole('button', { name: '测试连接' }).first().click()
    await page.getByText('8.0.33').first().waitFor()
  }
  await page.getByRole('button', { name: '新增数据源' }).click()
  const sourceDialog=page.getByRole('dialog')
  await sourceDialog.getByText('数据库密码', { exact: true }).waitFor()
  await sourceDialog.getByLabel('数据源名称').fill('浏览器验收动态数据源')
  await sourceDialog.getByLabel('数据库地址').fill('127.0.0.1')
  await sourceDialog.getByLabel('数据库名称').fill('smoke_source_db')
  await sourceDialog.getByLabel('数据库用户名').fill('metadata_reader')
  await sourceDialog.getByLabel('数据库密码').fill('smoke-secret-not-for-storage')
  await sourceDialog.getByRole('button', { name: '保存并测试连接' }).click()
  await page.getByText('浏览器验收动态数据源').first().waitFor()
  if (await page.evaluate(()=>Object.values(localStorage).some(v=>v.includes('smoke-secret-not-for-storage'))))
    throw new Error('Source password leaked into browser storage')
  const sourceRow=page.getByRole('row').filter({hasText:'浏览器验收动态数据源'})
  await sourceRow.getByRole('button',{name:'停用',exact:true}).click()
  await sourceRow.getByText('已停用').waitFor()
  if(await sourceRow.getByRole('button',{name:'开始扫描'}).isEnabled())throw new Error('Disabled Source can start scan')
  await sourceRow.getByRole('button',{name:'启用',exact:true}).click()
  await sourceRow.getByRole('button',{name:'编辑',exact:true}).click()
  if(await page.getByRole('dialog').getByLabel('数据库密码').inputValue())throw new Error('Edit Source echoed a password')
  await page.getByRole('button',{name:'取消',exact:true}).click()

  await page.goto('http://127.0.0.1:5174/scans', { waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: '元数据扫描' }).waitFor()
  await page.getByText('container_event').first().waitFor()
  await page.getByRole('button', { name: '查看字段', exact: true }).first().click()
  await page.getByRole('columnheader', { name: '字段说明' }).waitFor()
  await page.getByRole('columnheader', { name: '字段顺序' }).waitFor()

  await page.goto('http://127.0.0.1:5174/resources', { waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: '数据资源目录' }).waitFor()
  await page.getByRole('button', { name: '查看' }).first().click()
  await page.getByRole('heading', { name: '广州港集装箱作业事件数据集' }).waitFor()
  await page.getByRole('tab', { name: /字段元数据/ }).click()
  await page.getByText('container_no').first().waitFor()
  await page.getByRole('tab', { name: /接口能力/ }).click()
  await page.getByText('集装箱实时事件Topic').first().waitFor()

  await page.goto('http://127.0.0.1:5174/capabilities', { waitUntil: 'networkidle' })
  await page.getByRole('heading', { name: '接口能力管理' }).waitFor()
  await page.getByText('集装箱CDC变化流').first().waitFor()
  await page.getByRole('button', { name: '注册接口能力' }).click()
  const registration = page.getByRole('dialog')
  await registration.getByText('能力名称', { exact: true }).waitFor()
  await registration.getByRole('button', { name: '填入本机示例配置' }).click()
  if (await registration.getByLabel('接口路径', { exact: true }).inputValue() !== '/containers/events') throw new Error('Example path not filled')
  await registration.getByLabel('认证方式', { exact: true }).focus()
  await registration.getByLabel('认证方式', { exact: true }).press('ArrowDown')
  if (await page.getByRole('option', { name: 'SASL 认证', exact: true }).count()) throw new Error('REST offered Kafka-only authentication')
  await page.keyboard.press('Escape')
  await registration.getByLabel('能力类型', { exact: true }).focus()
  await registration.getByLabel('能力类型', { exact: true }).press('ArrowDown')
  await page.getByRole('option', { name: 'Kafka 消息主题', exact: true }).click()
  await registration.getByLabel('认证方式', { exact: true }).focus()
  await registration.getByLabel('认证方式', { exact: true }).press('ArrowDown')
  if (await page.getByRole('option', { name: '令牌认证', exact: true }).count()) throw new Error('Kafka offered REST-only authentication')
  await page.getByRole('option', { name: 'SASL 认证', exact: true }).click()
  await registration.getByLabel('能力类型', { exact: true }).focus()
  await registration.getByLabel('能力类型', { exact: true }).press('ArrowDown')
  await page.getByRole('option', { name: 'CDC 变化流', exact: true }).click()
  if (await registration.getByLabel('来源表', { exact: true }).getAttribute('readonly') === null) throw new Error('CDC table can drift from resource')
  await page.getByRole('button', { name: '取消' }).click()

  // Complete the report path using the explicit demo fixture.
  await page.goto('http://127.0.0.1:5174/scans', { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: '创建资源' }).first().click()
  const resourceDialog = page.getByRole('dialog')
  await resourceDialog.getByLabel('资源名称').fill('汇报验收集装箱事件资源')
  await resourceDialog.getByLabel('责任单位').fill('广州港数据管理部')
  await resourceDialog.getByLabel('业务描述').fill('汇报验收使用的集装箱作业事件元数据资源')
  await resourceDialog.getByRole('button', { name: '保存资源' }).click()
  await page.getByRole('heading', { name: '汇报验收集装箱事件资源' }).waitFor()
  await page.getByRole('tab', { name: /接口能力/ }).click()
  if (await page.getByRole('button', { name: /注册能力$/ }).isEnabled()) throw new Error('Draft resource can register capability')
  await page.getByRole('button', { name: '发布资源', exact:true }).click()
  await page.getByText('已发布', { exact:true }).first().waitFor()
  await page.getByRole('button', { name: '注册能力' }).click()
  const capabilityDialog = page.getByRole('dialog')
  await capabilityDialog.getByLabel('能力名称').fill('汇报验收查询接口')
  await capabilityDialog.getByLabel('接口路径').fill('/containers/events')
  await capabilityDialog.getByRole('button', { name: '保存能力' }).click()
  await page.getByText('汇报验收查询接口').first().waitFor()

  await page.goto('http://127.0.0.1:5174/dashboard', { waitUntil: 'networkidle' })
  await mkdir('.runtime', { recursive: true })
  await page.screenshot({ path: join('.runtime', 'dashboard.png'), fullPage: true })
  if (errors.length) throw new Error(`Browser errors: ${errors.join(' | ')}`)
  console.log('Browser smoke passed: login, dashboard, source dialog, scan fields, resource tabs, capability dialog, scan → resource → capability creation. Screenshot: .runtime/dashboard.png')
} finally {
  await browser?.close()
  await server.close()
}
