CREATE TABLE kafka_subscription_grant (
    grant_id VARCHAR(40) NOT NULL COMMENT '订阅授权编号；与REST共享关系独立',
    grant_name VARCHAR(120) NOT NULL COMMENT '授权名称',
    provider_subject_id VARCHAR(36) NOT NULL COMMENT '提供方主体编号',
    demand_subject_id VARCHAR(36) NOT NULL COMMENT '需求方主体编号',
    resource_id VARCHAR(40) NOT NULL COMMENT '所属已发布资源编号',
    capability_id VARCHAR(40) NOT NULL COMMENT 'Kafka主题能力编号',
    topic VARCHAR(249) NOT NULL COMMENT '申请时固定的精确主题名称；不允许通配符',
    auth_type VARCHAR(24) NOT NULL COMMENT '申请时固定的能力认证方式；本阶段仅SASL',
    consumer_group VARCHAR(100) NOT NULL COMMENT '为本授权预留的专属消费组；登记不表示已在Broker生效',
    scope VARCHAR(24) NOT NULL DEFAULT 'FULL_TOPIC' COMMENT '整主题范围：完整消息及可访问历史；不继承REST字段或数据时间策略',
    purpose VARCHAR(1000) NOT NULL COMMENT '申请用途',
    valid_from DATETIME(3) NOT NULL COMMENT '计划授权开始时间UTC；不是消息内数据时间筛选',
    valid_until DATETIME(3) NOT NULL COMMENT '计划授权结束时间UTC；登记本身不执行Broker到期撤权',
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT' COMMENT '审批状态：DRAFT草稿、PENDING待确认、APPROVED已确认、REVOKED已撤回申请',
    version INT NOT NULL DEFAULT 1 COMMENT '并发操作版本；每次有效修改加一',
    confirmed_at DATETIME(3) NULL COMMENT '管理员明确确认整主题范围的时间UTC',
    created_at DATETIME(3) NOT NULL COMMENT '创建时间UTC',
    updated_at DATETIME(3) NOT NULL COMMENT '最近修改时间UTC',
    PRIMARY KEY (grant_id),
    UNIQUE KEY uk_kafka_grant_group (consumer_group),
    KEY idx_kafka_grant_updated (updated_at,grant_id),
    CONSTRAINT fk_kafka_grant_provider FOREIGN KEY (provider_subject_id) REFERENCES sharing_subject(subject_id),
    CONSTRAINT fk_kafka_grant_demand FOREIGN KEY (demand_subject_id) REFERENCES sharing_subject(subject_id),
    CONSTRAINT fk_kafka_grant_resource FOREIGN KEY (resource_id) REFERENCES data_resource(resource_id),
    CONSTRAINT fk_kafka_grant_capability FOREIGN KEY (capability_id) REFERENCES capability(capability_id),
    CONSTRAINT chk_kafka_grant_scope CHECK (scope='FULL_TOPIC'),
    CONSTRAINT chk_kafka_grant_auth CHECK (auth_type='SASL'),
    CONSTRAINT chk_kafka_grant_status CHECK (status IN ('DRAFT','PENDING','APPROVED','REVOKED')),
    CONSTRAINT chk_kafka_grant_range CHECK (valid_from < valid_until)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Kafka整主题订阅独立审批；不保存凭据或业务消息，尚未执行Broker授权';

CREATE TABLE kafka_subscription_event (
    event_id BIGINT NOT NULL AUTO_INCREMENT COMMENT '审批历史流水号',
    grant_id VARCHAR(40) NOT NULL COMMENT '订阅授权编号',
    action VARCHAR(16) NOT NULL COMMENT '操作：CREATE、UPDATE、SUBMIT、CONFIRM、RETURN、REVOKE',
    from_status VARCHAR(16) NULL COMMENT '操作前审批状态；创建时为空',
    to_status VARCHAR(16) NOT NULL COMMENT '操作后审批状态',
    whole_topic_acknowledged BOOLEAN NOT NULL COMMENT '本次操作是否明确接受完整消息及历史范围；登记和确认必须为真',
    operator_name VARCHAR(120) NOT NULL COMMENT '原型管理员标签；尚不是服务端认证的可信身份',
    reason VARCHAR(1000) NOT NULL COMMENT '人工填写的操作原因',
    version INT NOT NULL COMMENT '操作完成后的授权版本',
    occurred_at DATETIME(3) NOT NULL COMMENT '操作时间UTC',
    PRIMARY KEY (event_id),
    UNIQUE KEY uk_kafka_event_version (grant_id,version),
    CONSTRAINT fk_kafka_event_grant FOREIGN KEY (grant_id) REFERENCES kafka_subscription_grant(grant_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Kafka订阅审批变更历史；与变更同事务，不表示Broker执行结果';
