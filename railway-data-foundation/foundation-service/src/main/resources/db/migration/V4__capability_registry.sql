CREATE TABLE capability (
    capability_id VARCHAR(40) NOT NULL,
    resource_id VARCHAR(40) NOT NULL,
    capability_name VARCHAR(120) NOT NULL,
    type VARCHAR(24) NOT NULL,
    http_method VARCHAR(8) NOT NULL DEFAULT '',
    endpoint VARCHAR(500) NOT NULL DEFAULT '',
    topic VARCHAR(249) NOT NULL DEFAULT '',
    source_table VARCHAR(64) NOT NULL DEFAULT '',
    protocol VARCHAR(40) NOT NULL DEFAULT '',
    auth_type VARCHAR(24) NOT NULL DEFAULT '',
    message_schema TEXT NULL,
    query_template_code VARCHAR(120) NOT NULL DEFAULT '',
    description VARCHAR(1000) NOT NULL DEFAULT '',
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    health_status VARCHAR(16) NOT NULL DEFAULT 'UNKNOWN',
    version INT NOT NULL DEFAULT 1,
    created_at DATETIME(3) NOT NULL,
    updated_at DATETIME(3) NOT NULL,
    PRIMARY KEY (capability_id),
    UNIQUE KEY uk_capability_name (resource_id, capability_name),
    KEY idx_capability_resource (resource_id, updated_at),
    CONSTRAINT fk_capability_resource FOREIGN KEY (resource_id) REFERENCES data_resource(resource_id),
    CONSTRAINT chk_capability_type CHECK (type IN ('REST_API','KAFKA_TOPIC','CDC_STREAM','READONLY_QUERY')),
    CONSTRAINT chk_capability_status CHECK (status IN ('DRAFT','VERIFIED','ENABLED','DISABLED','RETIRED')),
    CONSTRAINT chk_capability_health CHECK (health_status IN ('UNKNOWN','UP','DOWN','DEGRADED'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='资源访问能力登记；仅保存访问元数据和环境配置引用，不保存凭据或业务数据';
