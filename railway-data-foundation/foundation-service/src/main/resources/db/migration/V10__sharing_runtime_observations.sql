CREATE TABLE sharing_runtime_report (
    report_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '采集报告唯一编号，重试保持不变',
    collector_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '底座运维配置的受信任采集节点编号',
    collection_point VARCHAR(24) NOT NULL COMMENT '采集位置：REST_PROVIDER接口提供侧、KAFKA_PRODUCER消息生产侧，分别统计',
    window_start DATETIME(3) NOT NULL COMMENT 'UTC一分钟窗口起点，含起点',
    window_until DATETIME(3) NOT NULL COMMENT 'UTC一分钟窗口终点，不含终点',
    window_closed BOOLEAN NOT NULL COMMENT '采集节点是否声明该窗口关闭，不等于证明无丢失',
    content_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '规范化报告摘要，用于同编号内容冲突检测，不含凭据',
    accepted_events INT NOT NULL COMMENT '本报告新接收事件数量，不包含跨报告重复事件',
    duplicate_events INT NOT NULL COMMENT '本报告已接收过且内容一致的事件数量',
    received_at DATETIME(3) NOT NULL COMMENT '底座首次接收时刻，UTC，重试不覆盖',
    PRIMARY KEY (report_id),
    KEY idx_runtime_report_window (collector_id, collection_point, window_start),
    CONSTRAINT chk_runtime_report_point CHECK (collection_point IN ('REST_PROVIDER','KAFKA_PRODUCER')),
    CONSTRAINT chk_runtime_report_window CHECK (window_until = DATE_ADD(window_start, INTERVAL 1 MINUTE)),
    CONSTRAINT chk_runtime_report_counts CHECK (accepted_events >= 0 AND duplicate_events >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='共享运行摘要报告；只保存治理与计量元数据，不保存业务行或令牌';

CREATE TABLE sharing_runtime_event (
    event_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '操作事件唯一编号，跨报告重送仍使用相同编号',
    report_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '首次接收该事件的报告编号',
    trace_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '本次接口调用或消息生产的追踪编号',
    collector_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '已鉴权的采集节点编号，由底座赋值',
    collection_point VARCHAR(24) NOT NULL COMMENT '采集位置，区分接口调用和消息生产统计口径',
    relationship_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '已核对或尝试访问的关系编号，不代表访问获准',
    capability_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '访问能力编号；格式无效或未知可为空',
    subject_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '执行侧由可信访问决策获取的需求方编号；身份未知为空',
    resource_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '访问决策核对的资源编号，无法核对时为空',
    policy_id VARCHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '访问决策使用的策略编号，无法核对时为空',
    relationship_version INT NULL COMMENT '检查时的关系版本，无法核对时为空',
    policy_version INT NULL COMMENT '检查时的策略版本，无法核对时为空',
    started_at DATETIME(3) NOT NULL COMMENT '操作开始时刻，UTC，精度毫秒',
    completed_at DATETIME(3) NOT NULL COMMENT '操作完成时刻，UTC，决定窗口归属',
    outcome VARCHAR(12) NOT NULL COMMENT '操作结果：SUCCESS成功、DENIED拒绝、ERROR异常',
    reason_code VARCHAR(40) NOT NULL COMMENT '固定原因编号，不保存原始异常或输入值',
    http_status INT NOT NULL COMMENT '提供服务返回的HTTP状态',
    record_count BIGINT NOT NULL COMMENT '成功共享的业务记录数量，失败或拒绝为零',
    byte_count BIGINT NOT NULL COMMENT '成功响应体或事件JSON的字节数，不含传输头及网络开销',
    duration_ms BIGINT NOT NULL COMMENT '执行侧观测耗时，单位毫秒',
    topic VARCHAR(249) CHARACTER SET ascii COLLATE ascii_bin NULL COMMENT '消息生产的配置主题，接口查询为空',
    topic_partition INT NULL COMMENT '成功消息发送回执中的分区，接口查询为空',
    topic_offset BIGINT NULL COMMENT '成功消息发送回执中的位点，接口查询为空',
    content_digest CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL COMMENT '事件及采集位置摘要，用于防止跨报告重复计量或内容冲突',
    received_at DATETIME(3) NOT NULL COMMENT '底座首次接收该事件的时刻，UTC',
    PRIMARY KEY (event_id),
    UNIQUE KEY uq_runtime_event_trace (collector_id, collection_point, trace_id),
    KEY idx_runtime_event_completed (completed_at, event_id),
    KEY idx_runtime_event_resource (resource_id, completed_at),
    KEY idx_runtime_event_subject (subject_id, completed_at),
    KEY idx_runtime_event_relation (relationship_id, completed_at),
    CONSTRAINT fk_runtime_event_report FOREIGN KEY (report_id) REFERENCES sharing_runtime_report(report_id),
    CONSTRAINT chk_runtime_event_outcome CHECK (outcome IN ('SUCCESS','DENIED','ERROR')),
    CONSTRAINT chk_runtime_event_counts CHECK (record_count >= 0 AND byte_count >= 0 AND duration_ms >= 0),
    CONSTRAINT chk_runtime_event_time CHECK (completed_at >= started_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='接口调用与消息生产的审计摘要，保留编号与使用版本，不保存业务明细';
