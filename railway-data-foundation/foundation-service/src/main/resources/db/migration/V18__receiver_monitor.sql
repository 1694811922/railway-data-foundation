CREATE TABLE kafka_receiver_event (
 log_id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '底座接收技术事件内部编号',
 collector_id VARCHAR(64) NOT NULL COMMENT '服务端配置的接收采集节点，不由前端指定',
 event_id CHAR(36) NOT NULL COMMENT '接收端固定事件编号，用于幂等补报',
 task_id VARCHAR(40) NOT NULL COMMENT '外部接收任务编号，仅技术定位',
 grant_id VARCHAR(40) NOT NULL COMMENT '已登记订阅授权编号',
 resource_id VARCHAR(40) NOT NULL COMMENT '由底座授权记录确定的资源编号',
 capability_id VARCHAR(40) NOT NULL COMMENT '由底座授权记录确定的能力编号',
 provider_subject_id VARCHAR(40) NOT NULL COMMENT '由底座授权记录确定的提供方',
 demand_subject_id VARCHAR(40) NOT NULL COMMENT '由底座授权记录确定的需求方',
 topic VARCHAR(249) NOT NULL COMMENT '由底座冻结授权记录确定的主题',
 batch_id CHAR(36) NULL COMMENT '关联接收批次编号',
 report_id CHAR(36) NULL COMMENT '关联原消费摘要编号',
 event_type VARCHAR(32) NOT NULL COMMENT '固定技术事件枚举',
 outcome VARCHAR(16) NOT NULL COMMENT '技术事件结果，不代表业务处理成功',
 reason_code VARCHAR(40) NOT NULL COMMENT '固定原因枚举，禁止任意错误文本',
 operator_id VARCHAR(64) NULL COMMENT '接收端自报账号编号，不作为可信审批操作人',
 record_count INT NULL COMMENT '接收端自报读取条次',
 inserted_count INT NULL COMMENT '接收端自报新增落库数',
 duplicate_count INT NULL COMMENT '接收端自报相同位置去重数',
 byte_count BIGINT NULL COMMENT '接收端自报载荷字节',
 positions_json JSON NOT NULL COMMENT '仅分区和技术位置，不含业务键值或消息头',
 created_at DATETIME(3) NOT NULL COMMENT '接收端自报事件发生时间UTC',
 received_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) COMMENT '底座实际收到时间UTC',
 content_digest CHAR(64) NOT NULL COMMENT '固定事件内容摘要，冲突拒绝覆盖',
 UNIQUE KEY uk_receiver_event(collector_id,event_id),
 INDEX idx_receiver_time(created_at,log_id),
 INDEX idx_receiver_grant(grant_id,created_at),
 INDEX idx_receiver_batch(collector_id,task_id,batch_id,event_type),
 INDEX idx_receiver_report(collector_id,task_id,report_id,event_type),
 FOREIGN KEY(grant_id) REFERENCES kafka_subscription_grant(grant_id) ON DELETE CASCADE
) COMMENT '接收端自报技术事件，仅管理员监管，不含业务消息';
